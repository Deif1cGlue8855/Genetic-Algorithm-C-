int bx = 50;
int by = 50;
int br = 20;

struct point{
 int x, y, colls, goalAt;
};

//Inputs are U,D,L,R
std::vector<point> simulator(DNA testDNA, int start[2], int goal[2]){
    point testPos = {start[0], start[1], 0, -1};
    bool gotIt = false;
    
    std::vector<point> Path = {};

    for(int i = 0; i < testDNA.getLength(); i++){ 

        std::string command = testDNA.getValueAt(i);
        
        int dx = 0;
        int dy = 0;

        if(command == "U"){dy = -1;}
        else if(command == "D"){dy = 1;}
        else if(command == "L"){dx = -1;}
        else if(command == "R"){dx = 1;}

        if(map[testPos.y + dy][testPos.x + dx] != 1){
            testPos.y += dy;
            testPos.x += dx;
        }
        else{
            testPos.colls += 1;
        }

        Path.push_back(testPos);

        if(testPos.x == goal[0] && testPos.y == goal[1] && testPos.goalAt == -1){testPos.goalAt = Path.size() - 1;}
    }
    //Returns X, Y, how many moves that took
    return Path;
}

//Change it so it rewards reaching goal, deIncentivises hitting walls, scale it up to the map too
std::vector<float> fitnessFunction(std::vector<std::vector<point>> poses, int goal[2], int boardArea){
    float dx, dy;
    std::vector<float> allFitnesses;

    for(int i = 0; i < poses.size(); i++){
        
        //Reach goal reward
        const float goalR = 1000;
        //Collistion penalty
        const float collP = 1;
        //Path length penalty
        const float pathP = 1;
        //Distance penalty
        const float distP = 2;
        
        int pointLookAt = poses[i].size() - 1; 
        if(poses[i][pointLookAt].goalAt != -1){pointLookAt = poses[i][pointLookAt].goalAt;}
        

        dx = poses[i][pointLookAt].x - goal[0];
        dy = poses[i][pointLookAt].y - goal[1];
        

        //Missing squrt
        float dist = sqrt(dx * dx + dy * dy);

        float fitness = 0;

        if(poses[i][pointLookAt].x == goal[0] && poses[i][pointLookAt].y == goal[1]){
            fitness += goalR;
            fitness -= pathP * poses[i].size();
        }

        //fitness -= collP * poses[i][pointLookAt].colls;
        fitness -= collP * (poses[i][pointLookAt].colls * poses[i][pointLookAt].colls);
        fitness -= distP * dist;

        allFitnesses.push_back(fitness);
    }
    return allFitnesses;
}

int main(){

    //Sets the inputs to be only U, D, L and R
    std::vector<std::string> charSet = {"U", "D", "L", "R"};
    //Instantiating the GA
    GA ga(100,500, 0.07, 0.06, "PathSave.txt", charSet, 1);
    InitWindow(1000,1000,"GA Path finder");

    initRNG();

    int start[2] = {1,1};
    int goal[2] = {48,48};

    //Create the first gen 
    ga.makeFirstGen();
    //ga.loadGen();

    int IT = 0;
    std::vector<std::vector<point>> paths;

    while(!WindowShouldClose()){


        paths.clear();
        for(DNA x : ga.getDNAList()){
            paths.push_back(simulator(x, start, goal));
        }

        ga.setFitness(fitnessFunction(paths, goal, 100));

        ga.sortFitness();
        ga.crossover(200, 5, 10);
        ga.applyMutation();
        ga.saveGen();
            
        if(IT == 0){
            for(int it = 0; it < ga.getDNALength(); it++){

                BeginDrawing();
                ClearBackground(GRAY);
                //Prints the map
                for(int y = 0; y < by; y++){
                    
                    for(int x = 0; x < bx; x++){
                        //Sets colour to gray by default
                        Color colour = GRAY;

                        //If it's the start, draw it in red
                        if(x == start[0] && y == start[1]){
                            colour = RED;
                        }
                        //If it's the goal, draw it in green
                        else if(x == goal[0] && y == goal[1]){
                            colour = GREEN;
                        }
                        //Draw walls in black
                        else if(map[y][x] == 1){
                            colour = BLACK;
                        }
                        
                        //Draw the square with the colour chosen above 
                        DrawRectangle(br * x, br * y, br, br, colour);
                    }
                }    

                for(int i = 0; i < paths.size(); i++){

                    DrawRectangle(paths[i][it].x * br, paths[i][it].y * br, br, br, YELLOW);

                    if(paths[i][it].x == goal[0] && paths[i][it].y == goal[1]){
                        paths.erase(paths.begin() + i);
                    }
                    DrawText(std::to_string(100 - paths.size()).c_str(),0,40,20, WHITE);
                    DrawText(std::to_string(paths.size()).c_str(),0,60,20, WHITE);
                }
                //INFO / DEBUG PANEL

                DrawText(ga.getBestGuess().c_str(),0,0,20, WHITE);
                DrawText(std::to_string(ga.getGenNumber()).c_str(),0,20,20, WHITE);

                EndDrawing();
            }
            std::cout << ga.getBestFitness() << std::endl;
        }
        IT++;
        if(IT == 100){IT = 0;}

    }
    CloseWindow();

    return 0;
}
